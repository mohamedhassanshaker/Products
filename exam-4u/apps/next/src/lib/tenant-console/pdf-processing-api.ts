/** `POST /api/pdf-processing/sessions/:id/append`. `idempotencyKey`, if supplied, is sent as the
 * `Idempotency-Key` header (LLD §7.6) — safe to retry the identical call with the same key. */
export function appendToExamType(
  sessionId: string,
  input: { examTypeId: string; ids: string[] },
  idempotencyKey?: string,
): Promise<ExamTypeSummary> {
  const headers: Record<string, string> = {};
  if (idempotencyKey) headers['idempotency-key'] = idempotencyKey;
  return tenantFetch<ExamTypeSummary>(`/api/pdf-processing/sessions/${encodeURIComponent(sessionId)}/append`, {
    method: 'POST',
    headers,
    body: JSON.stringify(input),
  });
}
