/**
 * `POST /api/pdf-processing/upload` — multipart PDF upload. Same Fetch `FormData` client-side pattern
 * as `createExamTypeFromZip`; same documented "no first-class upload-progress event for a `FormData`
 * body" UX deviation from legacy's Angular `HttpClient.reportProgress` — a single indeterminate
 * "Uploading…" state for the whole request duration.
 */
export function uploadPdf(file: File, options: UploadPdfOptions = {}): Promise<UploadPdfResult> {
  const formData = new FormData();
  formData.append('file', file);
  if (options.contentTypeHint) formData.append('contentTypeHint', options.contentTypeHint);
  if (options.subjectId !== undefined) formData.append('subjectId', String(options.subjectId));
  if (options.curriculumId) formData.append('curriculumId', options.curriculumId);
  if (options.forceReprocess !== undefined) formData.append('forceReprocess', String(options.forceReprocess));

  return tenantFetch<UploadPdfResult>('/api/pdf-processing/upload', { method: 'POST', body: formData });
}

